static const char *const TAG = "hoymiles_dtu.cmt";

// Bit-bang half period (fallback transport). The CMT2300A samples SDIO on the rising SCLK edge and needs >=0.25 us setup,
// hold and chip-select spacing; 1 us per phase gives a ~330 kHz clock with a wide margin.
static constexpr uint32_t SPI_PHASE_US = 1;
// The FIFO chip select must stay high for >2 us between bytes (datasheet; both reference drivers use
// the same figure via cs_ena_posttrans).
static constexpr uint32_t FIFO_GAP_US = 4;
#ifdef USE_ESP32
// Hardware SPI clock. Both references run the chip at 4 MHz; 1 MHz leaves margin for flying leads
// and is still far faster than the bit-bang path. An exchange only moves tens of bytes.
static constexpr int HW_SPI_CLOCK_HZ = 1000000;
// Chip-select setup/hold around each transfer, in SCLK cycles: 2 cycles before, >2 us after (same
// values as OpenDTU's cmt_spi3.cpp, the more conservative of the two references).
static constexpr uint8_t HW_SPI_CS_PRE_CYCLES = 2;
static constexpr uint8_t HW_SPI_CS_POST_CYCLES = 2 * HW_SPI_CLOCK_HZ / 1000000;
#endif
// State transitions settle well under 100 us; give up after 4 ms so a wiring fault fails loudly
// instead of hanging the loop.
static constexpr uint16_t STATE_SWITCH_TRIES = 40;

// Register banks generated by CMOSTEK's RFPDK for the HM/HMS air interface: GFSK, 20 kbps, 20 kHz
// deviation, 4-byte sync word, variable-length packets with IBM-16 CRC, FEC on, 13 dBm. Byte i of a
// bank is written to register `base + i`. Identical to OpenDTU's cmt2300a_params_{860,900}.h and to
// Ahoy's cmtConfig table.
static constexpr uint8_t CMT_BANK_CMT_ADDR = 0x00;
static constexpr uint8_t CMT_BANK_CMT[12] = {0x00, 0x66, 0xEC, 0x1C, 0x70, 0x80, 0x14, 0x08, 0x11, 0x02, 0x02, 0x00};
static constexpr uint8_t CMT_BANK_SYSTEM_ADDR = 0x0C;
static constexpr uint8_t CMT_BANK_SYSTEM[12] = {0xAE, 0xE0, 0x35, 0x00, 0x00, 0xF4, 0x10, 0xE2, 0x42, 0x20, 0x0C, 0x81};
static constexpr uint8_t CMT_BANK_FREQUENCY_ADDR = 0x18;
// Only the frequency bank (and one data-rate byte, see below) differ per band.
static constexpr uint8_t CMT_BANK_FREQUENCY_860[8] = {0x42, 0x32, 0xCF, 0x82, 0x42, 0x27, 0x76, 0x12};
static constexpr uint8_t CMT_BANK_FREQUENCY_900[8] = {0x45, 0x46, 0x0A, 0x84, 0x45, 0x3B, 0xB1, 0x13};
static constexpr uint8_t CMT_BANK_DATA_RATE_ADDR = 0x20;
static constexpr uint8_t CMT_BANK_DATA_RATE[24] = {0xA6, 0xC9, 0x20, 0x20, 0xD2, 0x35, 0x0C, 0x0A,
                                                   0x9F, 0x4B, 0x29, 0x29, 0xC0, 0x14, 0x05, 0x53,
                                                   0x10, 0x00, 0xB4, 0x00, 0x00, 0x01, 0x00, 0x00};
// 0x27 (FSK4) is 0x0A on the 860 MHz band and 0x0B on the 900 MHz band.
static constexpr uint8_t CMT_REG_FSK4 = 0x27;
static constexpr uint8_t CMT_BANK_BASEBAND_ADDR = 0x38;
static constexpr uint8_t CMT_BANK_BASEBAND[29] = {0x12, 0x1E, 0x00, 0xAA, 0x06, 0x00, 0x00, 0x00, 0x00, 0x48,
                                                  0x5A, 0x48, 0x4D, 0x01, 0x1F, 0x00, 0x00, 0x00, 0x00, 0x00,
                                                  0xC3, 0x00, 0x00, 0x60, 0xFF, 0x00, 0x00, 0x1F, 0x10};
static constexpr uint8_t CMT_BANK_TX_ADDR = 0x55;
static constexpr uint8_t CMT_BANK_TX[11] = {0x70, 0x4D, 0x06, 0x00, 0x07, 0x50, 0x00, 0x53, 0x09, 0x3F, 0x7F};

// FREQ_OFS is in 2.5 kHz units; 100 steps = the 250 kHz channel spacing Hoymiles uses.
static constexpr uint8_t CMT_FREQUENCY_STEP_UNITS = 100;

// TX power words (TX8/TX9) for -10..+20 dBm on a 20 dBm matching network, from OpenDTU
// CMT2300A::setPALevel. Values above +16 dBm additionally need the CMT4 "double" bit.
static constexpr int8_t CMT_TX_POWER_MIN_DBM = -10;
static constexpr int8_t CMT_TX_POWER_MAX_DBM = 20;
static constexpr int8_t CMT_TX_POWER_DOUBLE_ABOVE_DBM = 16;
static constexpr uint16_t CMT_TX_POWER_WORDS[31] = {
    0x0501,  // -10 dBm
    0x0601, 0x0701, 0x0801, 0x0901, 0x0A01, 0x0B01, 0x0C01, 0x0D01, 0x0E01,
    0x1002,  // 0 dBm
    0x1302, 0x1602, 0x1902, 0x1C02, 0x1F03, 0x2403, 0x2804, 0x2D04, 0x3305,
    0x3906,  // +10 dBm
    0x4107, 0x4908, 0x5309, 0x5E0B, 0x6C0C, 0x7D0C, 0x4A0C, 0x580F, 0x6B12,
    0x8A18,  // +20 dBm
};

uint32_t Cmt2300a::base_frequency_hz(HmCmtRegion region) { return region == HM_REGION_EU ? 860000000UL : 900000000UL; }

uint32_t Cmt2300a::work_frequency_hz(HmCmtRegion region) { return region == HM_REGION_EU ? 865000000UL : 918000000UL; }

uint32_t Cmt2300a::boot_frequency_hz(HmCmtRegion region) { return region == HM_REGION_EU ? 868000000UL : 915000000UL; }

uint32_t Cmt2300a::legal_min_frequency_hz(HmCmtRegion region) {
  switch (region) {
    case HM_REGION_US:
      return 905000000UL;
    case HM_REGION_BRAZIL:
      return 915000000UL;
    case HM_REGION_EU:
    default:
      return 863000000UL;
  }
}

uint32_t Cmt2300a::legal_max_frequency_hz(HmCmtRegion region) {
  switch (region) {
    case HM_REGION_US:
      return 925000000UL;
    case HM_REGION_BRAZIL:
      return 928000000UL;
    case HM_REGION_EU:
    default:
      return 870000000UL;
  }
}

uint8_t Cmt2300a::channel_from_frequency(HmCmtRegion region, uint32_t frequency_hz) {
  const uint32_t base = base_frequency_hz(region);
  if (frequency_hz < base || frequency_hz % HM_CMT_CHANNEL_STEP_HZ != 0) {
    return 0xFF;
  }
  const uint32_t channel = (frequency_hz - base) / HM_CMT_CHANNEL_STEP_HZ;
  // Channel 0 is the bare base frequency and 0xFF is the error value, so both ends are excluded.
  if (channel == 0 || channel > 0xFE) {
    return 0xFF;
  }
  return static_cast<uint8_t>(channel);
}

bool Cmt2300a::setup() {
  if (sclk_ == nullptr || sdio_ == nullptr || csb_ == nullptr || fcsb_ == nullptr) {
    return false;
  }
  if (!setup_transport_()) {
    return false;
  }
  delay(2);

  write_register(CMT_REG_SOFT_RESET, 0xFF);
  delay(20);

  if (!switch_state_(CMT_GO_STBY, CMT_STA_STBY)) {
    ESP_LOGE(TAG, "chip did not enter standby (status=0x%02X)", chip_status());
    return false;
  }
  if (!chip_present()) {
    ESP_LOGE(TAG, "register readback failed - check sclk/sdio/csb/fcsb wiring");
    return false;
  }

  // Keep the register configuration across sleep, and do not let GPIO4 reset the chip.
  uint8_t mode_sta = read_register(CMT_REG_MODE_STA);
  mode_sta |= CMT_MASK_CFG_RETAIN;
  mode_sta &= ~CMT_MASK_RSTN_IN_EN;
  write_register(CMT_REG_MODE_STA, mode_sta);
  write_register(CMT_REG_EN_CTL, read_register(CMT_REG_EN_CTL) | CMT_MASK_LOCKING_EN);
  // Disable the low-frequency oscillator calibration; the sleep timer is unused.
  write_register(CMT_REG_SYS2, read_register(CMT_REG_SYS2) & 0x1F);
  clear_interrupt_flags_();

  configure_banks_();

  // xosc_aac_code[2:0] = 2, as the reference driver does after loading the banks.
  write_register(CMT_REG_CMT10, (read_register(CMT_REG_CMT10) & ~0x07) | 0x02);

  // GPIO2 -> INT1 (TX done), GPIO3 -> INT2 (packet received).
  write_register(CMT_REG_IO_SEL, CMT_GPIO2_SEL_INT1 | CMT_GPIO3_SEL_INT2);
  config_interrupt_(CMT_INT_SEL_TX_DONE, CMT_INT_SEL_PKT_OK);
  write_register(CMT_REG_INT_EN, CMT_MASK_TX_DONE_EN | CMT_MASK_PREAM_OK_EN | CMT_MASK_SYNC_OK_EN | CMT_MASK_CRC_OK_EN |
                                     CMT_MASK_PKT_DONE_EN);
  write_register(CMT_REG_FREQ_OFS, CMT_FREQUENCY_STEP_UNITS);
  // One merged 64-byte FIFO, so a 32-byte packet always fits whichever direction it travels.
  write_register(CMT_REG_FIFO_CTL, read_register(CMT_REG_FIFO_CTL) | CMT_MASK_FIFO_MERGE_EN);

  if (!set_tx_power()) {
    ESP_LOGW(TAG, "TX power %d dBm is out of range; keeping the configured 13 dBm default", tx_power_dbm_);
  }
  write_register(CMT_REG_FREQ_CHNL, channel_);

  // The configuration only takes effect after a sleep cycle.
  if (!switch_state_(CMT_GO_SLEEP, CMT_STA_SLEEP)) {
    return false;
  }
  delayMicroseconds(95);
  return switch_state_(CMT_GO_STBY, CMT_STA_STBY) && switch_state_(CMT_GO_SLEEP, CMT_STA_SLEEP);
}

bool Cmt2300a::chip_present() {
  const uint8_t saved = read_register(CMT_REG_PKT17);
  write_register(CMT_REG_PKT17, 0xAA);
  const uint8_t probe = read_register(CMT_REG_PKT17);
  write_register(CMT_REG_PKT17, saved);
  return probe == 0xAA;
}

void Cmt2300a::configure_banks_() {
  for (uint8_t i = 0; i < sizeof(CMT_BANK_CMT); i++) {
    write_register(CMT_BANK_CMT_ADDR + i, CMT_BANK_CMT[i]);
  }
  for (uint8_t i = 0; i < sizeof(CMT_BANK_SYSTEM); i++) {
    write_register(CMT_BANK_SYSTEM_ADDR + i, CMT_BANK_SYSTEM[i]);
  }
  const uint8_t *frequency = region_ == HM_REGION_EU ? CMT_BANK_FREQUENCY_860 : CMT_BANK_FREQUENCY_900;
  for (uint8_t i = 0; i < sizeof(CMT_BANK_FREQUENCY_860); i++) {
    write_register(CMT_BANK_FREQUENCY_ADDR + i, frequency[i]);
  }
  for (uint8_t i = 0; i < sizeof(CMT_BANK_DATA_RATE); i++) {
    write_register(CMT_BANK_DATA_RATE_ADDR + i, CMT_BANK_DATA_RATE[i]);
  }
  if (region_ != HM_REGION_EU) {
    write_register(CMT_REG_FSK4, 0x0B);
  }
  for (uint8_t i = 0; i < sizeof(CMT_BANK_BASEBAND); i++) {
    write_register(CMT_BANK_BASEBAND_ADDR + i, CMT_BANK_BASEBAND[i]);
  }
  for (uint8_t i = 0; i < sizeof(CMT_BANK_TX); i++) {
    write_register(CMT_BANK_TX_ADDR + i, CMT_BANK_TX[i]);
  }
}

void Cmt2300a::config_interrupt_(uint8_t int1_sel, uint8_t int2_sel) {
  uint8_t int1 = read_register(CMT_REG_INT1_CTL) & ~CMT_MASK_INT1_SEL;
  write_register(CMT_REG_INT1_CTL, int1 | (int1_sel & CMT_MASK_INT1_SEL));
  uint8_t int2 = read_register(CMT_REG_INT2_CTL) & ~CMT_MASK_INT2_SEL;
  write_register(CMT_REG_INT2_CTL, int2 | (int2_sel & CMT_MASK_INT2_SEL));
}

// Clear every pending interrupt flag, returning the set that was pending (in INT_FLAG /
// INT_EN bit positions). Port of CMT2300A_ClearInterruptFlags.
uint8_t Cmt2300a::clear_interrupt_flags_() {
  const bool active_low = (read_register(CMT_REG_INT1_CTL) & CMT_MASK_INT_POLAR) != 0;
  uint8_t flag1 = read_register(CMT_REG_INT_FLAG);
  uint8_t flag2 = read_register(CMT_REG_INT_CLR1);
  if (active_low) {
    flag1 = ~flag1;
    flag2 = ~flag2;
  }
  uint8_t clear1 = 0;
  uint8_t clear2 = 0;
  uint8_t pending = 0;
  if ((flag1 & CMT_MASK_LBD_FLG) != 0) {
    clear2 |= CMT_MASK_LBD_CLR;
  }
  if ((flag1 & (CMT_MASK_COL_ERR_FLG | CMT_MASK_PKT_ERR_FLG)) != 0) {
    clear2 |= CMT_MASK_PKT_DONE_CLR;  // both error flags clear via PKT_DONE
  }
  if ((flag1 & CMT_MASK_PREAM_OK_FLG) != 0) {
    clear2 |= CMT_MASK_PREAM_OK_CLR;
    pending |= CMT_MASK_PREAM_OK_FLG;
  }
  if ((flag1 & CMT_MASK_SYNC_OK_FLG) != 0) {
    clear2 |= CMT_MASK_SYNC_OK_CLR;
    pending |= CMT_MASK_SYNC_OK_FLG;
  }
  if ((flag1 & CMT_MASK_NODE_OK_FLG) != 0) {
    clear2 |= CMT_MASK_NODE_OK_CLR;
    pending |= CMT_MASK_NODE_OK_FLG;
  }
  if ((flag1 & CMT_MASK_CRC_OK_FLG) != 0) {
    clear2 |= CMT_MASK_CRC_OK_CLR;
    pending |= CMT_MASK_CRC_OK_FLG;
  }
  if ((flag1 & CMT_MASK_PKT_OK_FLG) != 0) {
    clear2 |= CMT_MASK_PKT_DONE_CLR;
    pending |= CMT_MASK_PKT_OK_FLG;
  }
  if ((flag2 & CMT_MASK_SL_TMO_FLG) != 0) {
    clear1 |= CMT_MASK_SL_TMO_CLR;
  }
  if ((flag2 & CMT_MASK_RX_TMO_FLG) != 0) {
    clear1 |= CMT_MASK_RX_TMO_CLR;
  }
  if ((flag2 & CMT_MASK_TX_DONE_FLG) != 0) {
    clear1 |= CMT_MASK_TX_DONE_CLR;
    pending |= CMT_MASK_TX_DONE_EN;
  }
  write_register(CMT_REG_INT_CLR1, clear1);
  write_register(CMT_REG_INT_CLR2, clear2);
  return pending;
}

void Cmt2300a::enable_read_fifo_() {
  const uint8_t value = read_register(CMT_REG_FIFO_CTL);
  write_register(CMT_REG_FIFO_CTL, value & ~(CMT_MASK_SPI_FIFO_RD_WR_SEL | CMT_MASK_FIFO_RX_TX_SEL));
}

void Cmt2300a::enable_write_fifo_() {
  const uint8_t value = read_register(CMT_REG_FIFO_CTL);
  write_register(CMT_REG_FIFO_CTL, value | CMT_MASK_SPI_FIFO_RD_WR_SEL | CMT_MASK_FIFO_RX_TX_SEL);
}

void Cmt2300a::clear_rx_fifo() { write_register(CMT_REG_FIFO_CLR, CMT_MASK_FIFO_CLR_RX); }

void Cmt2300a::clear_tx_fifo_() { write_register(CMT_REG_FIFO_CLR, CMT_MASK_FIFO_CLR_TX); }

void Cmt2300a::set_channel(uint8_t channel) {
  channel_ = channel;
  write_register(CMT_REG_FREQ_CHNL, channel);
}

bool Cmt2300a::set_tx_power() {
  if (tx_power_dbm_ < CMT_TX_POWER_MIN_DBM || tx_power_dbm_ > CMT_TX_POWER_MAX_DBM) {
    return false;
  }
  const uint16_t word = CMT_TX_POWER_WORDS[tx_power_dbm_ - CMT_TX_POWER_MIN_DBM];
  const uint8_t cmt4 = read_register(CMT_REG_CMT4);
  if (tx_power_dbm_ > CMT_TX_POWER_DOUBLE_ABOVE_DBM) {
    write_register(CMT_REG_CMT4, cmt4 | 0x01);
  } else {
    write_register(CMT_REG_CMT4, cmt4 & 0xFE);
  }
  write_register(CMT_REG_TX8, (word >> 8) & 0xFF);
  write_register(CMT_REG_TX9, word & 0xFF);
  return true;
}

bool Cmt2300a::start_listening() {
  if (!switch_state_(CMT_GO_STBY, CMT_STA_STBY)) {
    return false;
  }
  clear_interrupt_flags_();
  // SPI FIFO access has to be re-selected before the FIFO is cleared or used.
  enable_read_fifo_();
  clear_rx_fifo();
  if (!switch_state_(CMT_GO_RX, CMT_STA_RX)) {
    return false;
  }
  rx_mode_ = true;
  return true;
}

bool Cmt2300a::stop_listening() {
  rx_mode_ = false;
  clear_interrupt_flags_();
  return switch_state_(CMT_GO_SLEEP, CMT_STA_SLEEP);
}

bool Cmt2300a::packet_available() { return (read_register(CMT_REG_INT_FLAG) & CMT_MASK_RX_OK) == CMT_MASK_RX_OK; }

uint8_t Cmt2300a::read_packet(uint8_t *buffer, uint8_t max_len) {
  // Variable-length packets are stored length-prefixed, so the first FIFO byte is the payload size.
  uint8_t len = 0;
  read_fifo_(&len, 1);
  if (len == 0 || len > CMT_MAX_PACKET_LEN) {
    ESP_LOGW(TAG, "discarding RX frame with implausible length %u", len);
    clear_rx_fifo();
    clear_interrupt_flags_();
    return 0;
  }
  const uint8_t read_len = len > max_len ? max_len : len;
  read_fifo_(buffer, read_len);
  if (read_len < len) {
    // Drain the remainder so the next frame starts at a length byte.
    uint8_t discard;
    for (uint8_t i = read_len; i < len; i++) {
      read_fifo_(&discard, 1);
    }
  }
  clear_interrupt_flags_();
  return read_len;
}

bool Cmt2300a::begin_transmit(const uint8_t *payload, uint8_t len) {
  if (payload == nullptr || len == 0 || len > CMT_MAX_PACKET_LEN) {
    return false;
  }
  rx_mode_ = false;
  if (!switch_state_(CMT_GO_STBY, CMT_STA_STBY)) {
    return false;
  }
  clear_interrupt_flags_();
  enable_write_fifo_();
  clear_tx_fifo_();
  write_register(CMT_REG_PKT15, len);
  write_fifo_(payload, len);
  if ((read_register(CMT_REG_FIFO_FLAG) & CMT_MASK_TX_FIFO_NMTY_FLG) == 0) {
    ESP_LOGW(TAG, "TX FIFO stayed empty after loading %u bytes", len);
    return false;
  }
  return switch_state_(CMT_GO_TX, CMT_STA_TX);
}

void Cmt2300a::end_transmit() {
  clear_interrupt_flags_();
  switch_state_(CMT_GO_SLEEP, CMT_STA_SLEEP);
}

bool Cmt2300a::switch_state_(uint8_t go_command, uint8_t wait_state) {
  write_register(CMT_REG_MODE_CTL, go_command);
  for (uint16_t i = 0; i < STATE_SWITCH_TRIES; i++) {
    delayMicroseconds(100);
    if (chip_status() == wait_state) {
      return true;
    }
    // A very short packet can finish before TX is ever observed, and an already-queued packet can
    // complete the moment RX starts; both count as having reached the state.
    if (go_command == CMT_GO_TX && (read_register(CMT_REG_INT_CLR1) & CMT_MASK_TX_DONE_FLG) != 0) {
      return true;
    }
    if (go_command == CMT_GO_RX && (read_register(CMT_REG_INT_FLAG) & CMT_MASK_PKT_OK_FLG) != 0) {
      return true;
    }
  }
  ESP_LOGW(TAG, "state switch to 0x%02X timed out (status=0x%02X)", wait_state, chip_status());
  return false;
}

// --- 3-wire SPI transport ----------------------------------------------------------------------

bool Cmt2300a::setup_transport_() {
  hardware_spi_active_ = false;
#ifdef USE_ESP32
  if (use_hardware_spi_) {
    if (setup_hardware_spi_()) {
      hardware_spi_active_ = true;
      return true;
    }
    if (!hardware_spi_fallback_) {
      return false;
    }
    ESP_LOGW(TAG, "hardware SPI unavailable, falling back to bit-banged 3-wire SPI");
  }
#endif
  setup_bitbang_();
  return true;
}

void Cmt2300a::setup_bitbang_() {
  sclk_->setup();
  csb_->setup();
  fcsb_->setup();
  sdio_->setup();
  sdio_is_output_ = true;
  sclk_->digital_write(false);
  csb_->digital_write(true);
  fcsb_->digital_write(true);
  sdio_->digital_write(true);
}

#ifdef USE_ESP32
static int pin_number(GPIOPin *pin) { return static_cast<InternalGPIOPin *>(pin)->get_pin(); }

bool Cmt2300a::setup_hardware_spi_() {
  // SDIO is the bus' MOSI line; SPI_DEVICE_3WIRE makes the peripheral read on it as well. No MISO.
  spi_bus_config_t bus_config = {};
  bus_config.mosi_io_num = pin_number(sdio_);
  bus_config.miso_io_num = -1;
  bus_config.sclk_io_num = pin_number(sclk_);
  bus_config.quadwp_io_num = -1;
  bus_config.quadhd_io_num = -1;
  bus_config.max_transfer_sz = CMT_MAX_PACKET_LEN;
  bus_config.flags = SPICOMMON_BUSFLAG_MASTER;
  esp_err_t err = spi_bus_initialize(spi_host_, &bus_config, SPI_DMA_DISABLED);
  if (err != ESP_OK) {
    ESP_LOGE(TAG, "SPI host %d init failed: %s", static_cast<int>(spi_host_), esp_err_to_name(err));
    return false;
  }

  // Register frames: 1 command bit (R/W) + 7 address bits, then 8 data bits in either direction.
  spi_device_interface_config_t device_config = {};
  device_config.command_bits = 1;
  device_config.address_bits = 7;
  device_config.mode = 0;
  device_config.cs_ena_pretrans = HW_SPI_CS_PRE_CYCLES;
  device_config.cs_ena_posttrans = HW_SPI_CS_POST_CYCLES;
  device_config.clock_speed_hz = HW_SPI_CLOCK_HZ;
  device_config.spics_io_num = pin_number(csb_);
  device_config.flags = SPI_DEVICE_HALFDUPLEX | SPI_DEVICE_3WIRE;
  device_config.queue_size = 1;
  err = spi_bus_add_device(spi_host_, &device_config, &spi_register_);
  if (err == ESP_OK) {
    // FIFO bytes: no command/address phase, one byte per FCSB assertion.
    device_config.command_bits = 0;
    device_config.address_bits = 0;
    device_config.spics_io_num = pin_number(fcsb_);
    err = spi_bus_add_device(spi_host_, &device_config, &spi_fifo_);
  }
  if (err != ESP_OK) {
    ESP_LOGE(TAG, "SPI device add failed: %s", esp_err_to_name(err));
    if (spi_register_ != nullptr) {
      spi_bus_remove_device(spi_register_);
      spi_register_ = nullptr;
    }
    spi_bus_free(spi_host_);
    return false;
  }
  return true;
}
#endif

void Cmt2300a::sdio_output_() {
  if (!sdio_is_output_) {
    sdio_->pin_mode(gpio::FLAG_OUTPUT);
    sdio_is_output_ = true;
  }
}

void Cmt2300a::sdio_input_() {
  if (sdio_is_output_) {
    sdio_->pin_mode(gpio::FLAG_INPUT);
    sdio_is_output_ = false;
  }
}

void Cmt2300a::send_bits_(uint16_t value, uint8_t bits) {
  for (uint8_t i = bits; i > 0; i--) {
    sdio_->digital_write((value >> (i - 1)) & 0x01);
    delayMicroseconds(SPI_PHASE_US);
    sclk_->digital_write(true);  // the chip samples SDIO here
    delayMicroseconds(SPI_PHASE_US);
    sclk_->digital_write(false);
  }
}

uint8_t Cmt2300a::receive_bits_() {
  uint8_t value = 0;
  for (uint8_t i = 0; i < 8; i++) {
    sclk_->digital_write(true);
    delayMicroseconds(SPI_PHASE_US);
    value = static_cast<uint8_t>(value << 1) | (sdio_->digital_read() ? 0x01 : 0x00);
    sclk_->digital_write(false);
    delayMicroseconds(SPI_PHASE_US);
  }
  return value;
}

void Cmt2300a::write_register(uint8_t addr, uint8_t value) {
#ifdef USE_ESP32
  if (hardware_spi_active_) {
    spi_transaction_t trans = {};
    trans.cmd = 0;  // write
    trans.addr = addr & 0x7F;
    trans.length = 8;
    trans.tx_buffer = &value;
    ESP_ERROR_CHECK_WITHOUT_ABORT(spi_device_polling_transmit(spi_register_, &trans));
    return;
  }
#endif
  sdio_output_();
  sclk_->digital_write(false);
  csb_->digital_write(false);
  delayMicroseconds(SPI_PHASE_US);
  // 16-bit frame: bit15 = 0 (write), bits 14..8 = address, bits 7..0 = data.
  send_bits_(static_cast<uint16_t>(addr & 0x7F) << 8 | value, 16);
  delayMicroseconds(SPI_PHASE_US);
  csb_->digital_write(true);
  delayMicroseconds(SPI_PHASE_US);
}

uint8_t Cmt2300a::read_register(uint8_t addr) {
#ifdef USE_ESP32
  if (hardware_spi_active_) {
    uint8_t value = 0;
    spi_transaction_t trans = {};
    trans.cmd = 1;  // read
    trans.addr = addr & 0x7F;
    trans.rxlength = 8;
    trans.rx_buffer = &value;
    ESP_ERROR_CHECK_WITHOUT_ABORT(spi_device_polling_transmit(spi_register_, &trans));
    return value;
  }
#endif
  sdio_output_();
  sclk_->digital_write(false);
  csb_->digital_write(false);
  delayMicroseconds(SPI_PHASE_US);
  // 8-bit command: bit7 = 1 (read), bits 6..0 = address. The chip then drives the 8 data bits on the
  // same wire, so SDIO has to be released first.
  send_bits_(0x80 | (addr & 0x7F), 8);
  sdio_input_();
  const uint8_t value = receive_bits_();
  csb_->digital_write(true);
  sdio_output_();
  sdio_->digital_write(true);
  delayMicroseconds(SPI_PHASE_US);
  return value;
}

void Cmt2300a::write_fifo_(const uint8_t *data, uint8_t len) {
#ifdef USE_ESP32
  if (hardware_spi_active_) {
    spi_device_acquire_bus(spi_fifo_, portMAX_DELAY);
    spi_transaction_t trans = {};
    trans.length = 8;
    for (uint8_t i = 0; i < len; i++) {
      trans.tx_buffer = data + i;
      ESP_ERROR_CHECK_WITHOUT_ABORT(spi_device_polling_transmit(spi_fifo_, &trans));
      delayMicroseconds(FIFO_GAP_US);
    }
    spi_device_release_bus(spi_fifo_);
    return;
  }
#endif
  sdio_output_();
  for (uint8_t i = 0; i < len; i++) {
    sclk_->digital_write(false);
    fcsb_->digital_write(false);
    delayMicroseconds(SPI_PHASE_US);
    send_bits_(data[i], 8);
    delayMicroseconds(SPI_PHASE_US);
    fcsb_->digital_write(true);
    delayMicroseconds(FIFO_GAP_US);
  }
}

void Cmt2300a::read_fifo_(uint8_t *data, uint8_t len) {
#ifdef USE_ESP32
  if (hardware_spi_active_) {
    spi_device_acquire_bus(spi_fifo_, portMAX_DELAY);
    spi_transaction_t trans = {};
    trans.rxlength = 8;
    for (uint8_t i = 0; i < len; i++) {
      trans.rx_buffer = data + i;
      ESP_ERROR_CHECK_WITHOUT_ABORT(spi_device_polling_transmit(spi_fifo_, &trans));
      delayMicroseconds(FIFO_GAP_US);
    }
    spi_device_release_bus(spi_fifo_);
    return;
  }
#endif
  for (uint8_t i = 0; i < len; i++) {
    sdio_input_();
    sclk_->digital_write(false);
    fcsb_->digital_write(false);
    delayMicroseconds(SPI_PHASE_US);
    data[i] = receive_bits_();
    fcsb_->digital_write(true);
    delayMicroseconds(FIFO_GAP_US);
  }
  sdio_output_();
  sdio_->digital_write(true);
}

